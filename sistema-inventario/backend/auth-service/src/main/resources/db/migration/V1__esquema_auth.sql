-- =====================================================================
-- auth-service · esquema (PostgreSQL)
-- Autenticación y autorización (no forman parte de las 9 entidades del Avance 1).
-- Los roles y usuarios de prueba los crea la clase DatosIniciales al arrancar,
-- porque las contraseñas se guardan cifradas con BCrypt.
-- =====================================================================

CREATE TABLE rol (
    id_rol       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30)  NOT NULL,
    descripcion  VARCHAR(150),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE usuario (
    id_usuario       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(50)  NOT NULL,
    password_hash    VARCHAR(100) NOT NULL,
    nombre_completo  VARCHAR(120) NOT NULL,
    email            VARCHAR(100) NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Referencia opcional a experto_soporte de catalogos-service (otra base, sin FK física)
    id_experto       INTEGER,
    CONSTRAINT uq_usuario_username UNIQUE (username),
    CONSTRAINT uq_usuario_email    UNIQUE (email)
);

CREATE TABLE usuario_rol (
    id_usuario  INTEGER NOT NULL,
    id_rol      INTEGER NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol) ON DELETE RESTRICT
);
